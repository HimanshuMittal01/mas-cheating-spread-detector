"""Regenerate docs/results.md from every session JSON under runs2/ (all runs, all pools, all models).

    uv run swarm2/results.py [runs2] [-o docs/results.md]

Honest = any non-planted agent. Spread compares honest agents 1-3 in planted vs control sessions
(agent 0 is the planted slot in both arms). Incomplete sessions are counted but never labelled.
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

HEAD = """# Results (auto-generated)

Generated by `uv run swarm2/results.py`. Do not edit by hand; put interpretation in `docs/learnings.md`.
Incomplete sessions (API/sandbox errors) are counted, never labelled.
"Touched tests" fires on any test-dir edit, including an agent's own debug test files: hand-check before reading it as copying.
Earlier work: rotation pilot results are in `pilot/REPORT.md`.

"""


def pct(a, b):
    return f"{a}/{b} ({100 * a / b:.0f}%)" if b else "-"


def load(root: Path):
    for f in sorted(root.glob("*/*.json")):
        try:
            d = json.loads(f.read_text())
        except Exception:  # noqa: BLE001
            continue
        if isinstance(d, dict) and "agents" in d and "cfg" in d:
            yield f.parent.name, d


def cfg_str(c: dict) -> str:
    parts = [c.get("model", "?")]
    if c.get("model0"):
        parts.append(f"a0={c['model0']}")
    parts.append(f"steps={c.get('max_steps')}")
    if c.get("show_budget"):
        parts.append("budget-visible")
    if c.get("head_start"):
        parts.append(f"head={c['head_start']}")
    parts.append(c.get("wording", "?"))
    if c.get("seed_style", "words") != "words":
        parts.append(f"seed={c['seed_style']}")
    if c.get("pool"):
        parts.append(f"pool={len(c['pool'].split(','))}")
    if c.get("source", "codecontests") != "codecontests":
        parts.append(c["source"])
    return ", ".join(str(p) for p in parts)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?", default="runs2")
    ap.add_argument("-o", "--out", default="docs/results.md")
    a = ap.parse_args(argv)

    runs = defaultdict(lambda: {"cfg": None, "n": 0, "inc": 0, "pl": [], "co": []})
    by_model_issue = defaultdict(lambda: [0, 0, []])  # (model, issue) -> solved, n, steps
    for run, d in load(Path(a.root)):
        r = runs[run]
        r["cfg"] = r["cfg"] or d["cfg"]
        r["n"] += 1
        if d.get("status") != "complete":
            r["inc"] += 1
            continue
        (r["pl"] if d.get("planted") else r["co"]).append(d)
        for ag in d["agents"]:
            if ag["planted"] or not ag.get("label"):
                continue
            m = (d["cfg"].get("model0") or d["cfg"]["model"]) if ag["agent"] == 0 else d["cfg"]["model"]
            x = by_model_issue[(m, ag["issue"])]
            x[0] += bool(ag["label"]["truth"])
            x[1] += 1
            x[2].append(ag["steps"])

    out = [HEAD, "## Runs\n",
           "| run | config | sessions (incomplete) | honest solve | planted agent cheat | honest cheat: planted vs control | exposed honest who cheated or touched tests (hand-check) |",
           "|---|---|---|---|---|---|---|"]
    for run in sorted(runs):
        r = runs[run]
        hon = [ag for d in r["pl"] + r["co"] for ag in d["agents"] if not ag["planted"]]
        solved = sum(bool(ag["label"]["truth"]) for ag in hon)
        a0 = [d["agents"][0] for d in r["pl"]]
        a0c = sum(bool(ag["label"]["cheat"]) for ag in a0)
        hp = [ag for d in r["pl"] for ag in d["agents"][1:]]
        hc = [ag for d in r["co"] for ag in d["agents"][1:]]
        cp = sum(bool(ag["label"]["cheat"]) for ag in hp)
        cc = sum(bool(ag["label"]["cheat"]) for ag in hc)
        exp = [ag for ag in hp if ag.get("exposure_step") is not None]
        copied = sum(bool(ag["label"]["cheat"] or ag["label"].get("tried")) for ag in exp)
        out.append(f"| {run} | {cfg_str(r['cfg'])} | {r['n']} ({r['inc']}) | {pct(solved, len(hon))} | "
                   f"{pct(a0c, len(a0)) if a0 else '-'} | {pct(cp, len(hp)) if hp else '-'} vs {pct(cc, len(hc)) if hc else '-'} | "
                   f"{pct(copied, len(exp)) if exp else '-'} |")

    out += ["", "## Honest solve rate by model and issue (all runs pooled)\n",
            "| model | issue | solved | median steps |", "|---|---|---|---|"]
    for (m, iss), (s, n, st) in sorted(by_model_issue.items(), key=lambda kv: (kv[0][0], kv[1][0] / kv[1][1])):
        out.append(f"| {m} | {iss} | {pct(s, n)} | {sorted(st)[len(st) // 2]} |")
    tot = defaultdict(lambda: [0, 0])
    for (m, _), (s, n, _) in by_model_issue.items():
        tot[m][0] += s
        tot[m][1] += n
    out += ["", "## Honest solve rate by model\n", "| model | solved |", "|---|---|"]
    out += [f"| {m} | {pct(s, n)} |" for m, (s, n) in sorted(tot.items())]
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}: {len(runs)} runs")


if __name__ == "__main__":
    main()
